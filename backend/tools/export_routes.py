"""
Export the live route inventory for the frontend's route-inventory test.

  python tools/export_routes.py

Writes ../web/tests/fixtures/backend-routes.json: every method+path FastAPI
actually serves, taken from app.openapi() rather than from a hand-kept list.
The generated schema is the only honest source — a router that was never passed
to include_router has decorators that look right and a path that 404s.

Why the frontend reads a committed fixture instead of calling a running server:
its test suite has to pass in CI and on a laptop with no database, and a check
that silently skips when the backend is down is a check that stops running. The
fixture makes the inventory a reviewable artefact — a diff on this file in a pull
request is exactly the moment to ask whether the frontend knows a route moved.

Re-run this after adding, removing or renaming a route. web's
route-inventory.test.ts fails with a message pointing back here when they drift.
"""
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))

from app.main import app  # noqa: E402  (import after sys.path fix)

OUT = (
    pathlib.Path(__file__).resolve().parents[2]
    / "web"
    / "tests"
    / "fixtures"
    / "backend-routes.json"
)

# Mobile gets its own copy rather than reaching across into web/. Two files with
# one generator beats one file two projects import by relative path — and mobile is
# where two of the four dead routes were found (GET /jobs/me, and a cancel that
# sent the wrong field name), so it needs the same guard.
OUT_MOBILE = (
    pathlib.Path(__file__).resolve().parents[2]
    / "mobile"
    / "tests"
    / "fixtures"
    / "backend-routes.json"
)

_METHODS = ("get", "post", "patch", "put", "delete")


def inventory() -> list[str]:
    """Every served route as "METHOD /path", sorted."""
    spec = app.openapi()
    routes = {
        f"{method.upper()} {path}"
        for path, operations in spec["paths"].items()
        for method in operations
        if method.lower() in _METHODS
    }
    return sorted(routes)


def main() -> int:
    routes = inventory()
    payload = (
        json.dumps(
            {
                "_comment": (
                    "GENERATED by backend/tools/export_routes.py from "
                    "app.openapi(). Do not edit by hand — re-run the script."
                ),
                "routes": routes,
            },
            indent=2,
        )
        + "\n"
    )
    for target in (OUT, OUT_MOBILE):
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(payload, encoding="utf-8")
        print(f"wrote {target} with {len(routes)} routes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
